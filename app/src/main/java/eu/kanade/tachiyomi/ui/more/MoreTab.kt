data object MoreTab : Tab {

    override val options: TabOptions
        @Composable
        get() {
            val isSelected = LocalTabNavigator.current.current.key == key
            val image = AnimatedImageVector.animatedVectorResource(R.drawable.animated_more)
            return TabOptions(
                index = 4u,
                title = stringResource(MR.strings.label_more),
                icon = rememberAnimatedVectorPainter(image, isSelected),
            )
        }

    override suspend fun onReselect(navigator: Navigator) {
        navigator.push(SettingsScreen())
    }

    @Composable
    override fun Content() {
        val navigator = LocalNavigator.currentOrThrow
        val viewModel = metroViewModel<MoreViewModel>()
        val downloadQueueState by viewModel.downloadQueueState.collectAsState()
        val overview by viewModel.overview.collectAsState()

        // Refresh "继续阅读" every time this tab is shown.
        LaunchedEffect(Unit) {
            viewModel.refreshContinueReading()
        }

        MoreScreen(
            overview = overview,
            downloadQueueStateProvider = { downloadQueueState },
            onClickContinueReading = { navigator.push(MangaScreen(it, true)) },
            onClickDownloadQueue = { navigator.push(DownloadQueueScreen) },
            onClickCategories = { navigator.push(CategoryScreen()) },
            onClickStats = { navigator.push(StatsScreen()) },
            onClickTracking = { navigator.push(SettingsScreen(SettingsScreen.Destination.Tracking)) },
            onClickDataAndStorage = { navigator.push(SettingsScreen(SettingsScreen.Destination.DataAndStorage)) },
            onClickSettings = { navigator.push(SettingsScreen()) },
            onClickAbout = { navigator.push(SettingsScreen(SettingsScreen.Destination.About)) },
        )
    }
}

@Inject
@ViewModelKey
@ContributesIntoMap(AppScope::class)
class MoreViewModel(
    private val downloadManager: DownloadManager,
    getLibraryManga: GetLibraryManga,
    private val historyRepository: HistoryRepository,
) : ViewModel() {

    private val lastHistory = MutableStateFlow<HistoryWithRelations?>(null)

    val overview: StateFlow<MoreOverview> = combine(
        getLibraryManga.subscribe(),
        lastHistory,
    ) { library, last ->
        MoreOverview(
            libraryCount = library.size,
            unreadCount = library.sumOf { it.unreadCount },
            continueReading = last,
        )
    }.stateIn(viewModelScope, SharingStarted.WhileSubscribed(5_000), MoreOverview())

    private var _downloadQueueState: MutableStateFlow<DownloadQueueState> = MutableStateFlow(DownloadQueueState.Stopped)
    val downloadQueueState: StateFlow<DownloadQueueState> = _downloadQueueState.asStateFlow()

    init {
        refreshContinueReading()

        // Handle running/paused status change and queue progress updating
        viewModelScope.launch {
            combine(
                downloadManager.isDownloaderRunning,
                downloadManager.queueState,
            ) { isRunning, downloadQueue -> Pair(isRunning, downloadQueue.size) }
                .collectLatest { (isDownloading, downloadQueueSize) ->
                    val pendingDownloadExists = downloadQueueSize != 0
                    _downloadQueueState.value = when {
                        !pendingDownloadExists -> DownloadQueueState.Stopped
                        !isDownloading -> DownloadQueueState.Paused(downloadQueueSize)
                        else -> DownloadQueueState.Downloading(downloadQueueSize)
                    }
                }
        }
    }

    fun refreshContinueReading() {
        viewModelScope.launch {
            lastHistory.value = runCatching { historyRepository.getLastHistory() }.getOrNull()
        }
    }
}

/**
 * Lightweight summary shown on the "我的" tab: a resume shortcut plus library counters.
 */
data class MoreOverview(
    val libraryCount: Int = 0,
    val unreadCount: Long = 0,
    val continueReading: HistoryWithRelations? = null,
)

sealed interface DownloadQueueState {
    data object Stopped : DownloadQueueState
    data class Paused(val pending: Int) : DownloadQueueState
    data class Downloading(val pending: Int) : DownloadQueueState
}
